const form = document.getElementById('sentiment-form');
const input = document.getElementById('text-input');
const count = document.getElementById('char-count');
const analyzeBtn = document.getElementById('analyze-btn');
const buttonLabel = document.getElementById('button-label');
const clearBtn = document.getElementById('clear-btn');
const toast = document.getElementById('toast');
const colors = {sadness:'#6b9df5',joy:'#ffb940',love:'#ed70a4',anger:'#f06479',fear:'#9670f5',surprise:'#39b98b'};
const emojis = {sadness:'🌧️',joy:'☀️',love:'💗',anger:'🔥',fear:'🌙',surprise:'✨'};
let toastTimer;
function showToast(message, error=false){toast.textContent=message;toast.className='toast show'+(error?' error':'');clearTimeout(toastTimer);toastTimer=setTimeout(()=>toast.className='toast',3000);}
function updateCount(){count.textContent=`${input.value.length} / 2000`;}
input.addEventListener('input',updateCount);
document.querySelectorAll('[data-example]').forEach(btn=>btn.addEventListener('click',()=>{input.value=btn.dataset.example;updateCount();input.focus();}));
clearBtn.addEventListener('click',()=>{input.value='';updateCount();input.focus();});
function renderScores(scores,predictedKey){
 const list=document.getElementById('score-list');list.innerHTML='';
 // Bars compare each raw SVM decision margin on a min-max visual scale; they are not probabilities.
 const values=scores.map(s=>Number(s.score));const min=Math.min(...values),max=Math.max(...values);const span=max-min||1;
 const ordered=[...scores].sort((a,b)=>Number(b.score)-Number(a.score));
 ordered.forEach(item=>{
  const key=item.name.toLowerCase();const row=document.createElement('div');row.className='score-row'+(key===predictedKey?' top-score':'');
  const label=document.createElement('div');label.className='score-label';const dot=document.createElement('i');dot.className=`emotion-dot ${key}`;const name=document.createElement('span');name.textContent=item.name;label.append(dot,name);
  const track=document.createElement('div');track.className='score-track';const fill=document.createElement('div');fill.className='score-fill';fill.style.background=colors[key]||'#9271f8';fill.style.width=`${Math.max(5,((Number(item.score)-min)/span)*100)}%`;track.append(fill);
  const value=document.createElement('span');value.className='score-value';value.textContent=Number(item.score).toFixed(3);row.append(label,track,value);list.append(row);
 });
}
form.addEventListener('submit',async event=>{
 event.preventDefault();const text=input.value.trim();if(!text){showToast('Write a sentence first to discover its emotion.',true);input.focus();return;}
 analyzeBtn.disabled=true;buttonLabel.textContent='Reading your words…';
 try{
  const response=await fetch('/predict',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({text})});
  const data=await response.json();if(!response.ok)throw new Error(data.error||'Unable to analyze this sentence.');
  const key=data.sentiment_key;document.getElementById('result-emoji').textContent=data.emoji||emojis[key]||'✦';document.getElementById('result-title').textContent=data.sentiment;document.getElementById('result-description').textContent=data.description;document.getElementById('result-note').textContent='Prediction generated by your saved Linear SVM model.';
  document.getElementById('prediction-area').style.background=`linear-gradient(145deg, ${colors[key]}18, #f3f7ff)`;document.getElementById('result-panel').style.borderColor=`${colors[key]}88`;renderScores(data.scores,key);showToast(`Your sentence leans toward ${data.sentiment.toLowerCase()}.`);
  document.getElementById('result-panel').scrollIntoView({behavior:'smooth',block:'nearest'});
 }catch(error){showToast(error.message||'Something went wrong. Check that Flask is running.',true);}
 finally{analyzeBtn.disabled=false;buttonLabel.textContent='Analyze my sentence';}
});
